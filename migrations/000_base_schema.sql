-- 000: base schema (Batch 1). Creates the foundational objects that existed before
-- migration 001 and that no other migration creates, so a fresh, EMPTY database can be
-- built from version control alone:  000 -> 001 -> 002 -> 003.
--
-- Source: schema-only, read-only extraction (pg_dump --schema-only) of the application
-- database on 2026-11-15, minus every object created by 001-003. No data was copied.
-- Not included: the unused experiment table public.vector_test.
--
-- Prerequisites: PostgreSQL 18 with the pgvector extension files installed on the server
-- (CREATE EXTENSION needs a role allowed to create extensions, e.g. the database owner).
--
-- Idempotent: every statement uses IF NOT EXISTS. On an existing database (rag_db) it is
-- a no-op and does NOT alter existing tables. Constraint, sequence and index names match
-- the existing database. Rollback: none (base schema; drop the database instead).
BEGIN;

CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

-- Conversation ids are generated by the application (uuid4).
CREATE TABLE IF NOT EXISTS public.conversations (
    id uuid PRIMARY KEY,
    title text,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    summary text DEFAULT ''::text,
    summary_up_to_message_id bigint NOT NULL DEFAULT 0,
    memory_extraction_up_to_message_id bigint NOT NULL DEFAULT 0
);

-- messages.context_excluded is added by 001.
CREATE TABLE IF NOT EXISTS public.messages (
    id bigserial PRIMARY KEY,
    conversation_id uuid NOT NULL REFERENCES public.conversations (id) ON DELETE CASCADE,
    role character varying(20) NOT NULL,
    content text NOT NULL,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_conversation
    ON public.messages USING btree (conversation_id, created_at);

-- Legacy single-source column source_message_id is kept and still written; the full
-- provenance lives in memory_sources (002/003).
CREATE TABLE IF NOT EXISTS public.conversation_memories (
    id bigserial PRIMARY KEY,
    conversation_id uuid NOT NULL REFERENCES public.conversations (id) ON DELETE CASCADE,
    memory text NOT NULL,
    embedding public.vector(384) NOT NULL,
    source_message_id bigint REFERENCES public.messages (id) ON DELETE SET NULL,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_conversation_memories
    ON public.conversation_memories USING btree (conversation_id);

-- The UNIQUE key is required by ingest_pdf's INSERT ... ON CONFLICT and stale-chunk cleanup.
-- embedding dimension 384 = EMBEDDING_DIM default (all-MiniLM-L6-v2).
CREATE TABLE IF NOT EXISTS public.document_chunks (
    id bigserial PRIMARY KEY,
    document_name text NOT NULL,
    page_number integer NOT NULL,
    chunk_id integer NOT NULL,
    content text NOT NULL,
    embedding public.vector(384) NOT NULL,
    UNIQUE (document_name, page_number, chunk_id)
);

COMMIT;
